"""Generate a Daily Markdown Report

This script reads from data/signals.jsonl, computes basic statistics, 
and generates a comprehensive Markdown report saved to data/daily_report.md.
"""
import json
import logging
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
import sys

# Ensure repo root on sys.path
sys.path.insert(0, str(Path(__file__).parent.parent))

from src.engine.schema import Signal

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

def main():
    data_dir = Path("data")
    sig_path = data_dir / "signals.jsonl"
    out_path = data_dir / "Daily_Risk_Report.md"
    
    if not sig_path.exists():
        logger.error(f"Signals file not found at {sig_path}")
        return

    signals: list[Signal] = []
    with sig_path.open("r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            try:
                signals.append(Signal.model_validate_json(line))
            except Exception as e:
                logger.warning(f"Failed to parse signal: {e}")

    if not signals:
        logger.warning("No signals to report.")
        return

    signals.sort(key=lambda s: s.ts)
    
    total_signals = len(signals)
    entities = set(s.entity for s in signals)
    critical_events = [s for s in signals if s.impact >= 7]
    
    event_counts = defaultdict(int)
    for s in signals:
        event_counts[s.event_type] += 1

    entity_mentions = defaultdict(int)
    entity_sentiment = defaultdict(list)
    for s in signals:
        entity_mentions[s.entity] += 1
        entity_sentiment[s.entity].append(s.sentiment)
        
    avg_sentiment = {
        ent: sum(scores) / len(scores) 
        for ent, scores in entity_sentiment.items()
    }
    
    top_entities = sorted(
        entity_mentions.keys(), 
        key=lambda e: entity_mentions[e], 
        reverse=True
    )[:10]

    report_date = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M")
    
    lines = [
        "# 📊 Daily Financial Risk & Rebalance Report",
        f"**Generated:** {report_date} UTC  ",
        "---",
        "## 1. Executive Summary",
        f"- **Total Signals Processed:** {total_signals}",
        f"- **Unique Entities Analyzed:** {len(entities)}",
        f"- **Critical Alerts (Impact ≥ 7):** {len(critical_events)}",
        "",
        "## 2. Event Breakdown",
        "| Event Type | Count |",
        "|------------|-------|"
    ]
    
    for etype, count in sorted(event_counts.items(), key=lambda x: x[1], reverse=True):
        lines.append(f"| {etype} | {count} |")
        
    lines.extend([
        "",
        "## 3. Top Entities in Focus",
        "| Entity | Mentions | Avg Sentiment |",
        "|--------|----------|---------------|"
    ])
    
    for ent in top_entities:
        sent = avg_sentiment[ent]
        emoji = "🔴" if sent <= -0.2 else ("🟢" if sent >= 0.2 else "⚪")
        lines.append(f"| **{ent}** | {entity_mentions[ent]} | {sent:+.2f} {emoji} |")

    lines.extend([
        "",
        "## 4. Critical Event Log (High Impact)",
        "The following events triggered immediate portfolio stress tests and index rebalancing:",
        ""
    ])
    
    if not critical_events:
        lines.append("*No critical events recorded during this period.*")
    else:
        for ce in critical_events:
            ev_text = ce.evidence[0] if ce.evidence else "No evidence text."
            lines.extend([
                f"### [{ce.entity}] {ce.event_type} (Impact: {ce.impact}/10)",
                f"- **Time:** {ce.ts.strftime('%Y-%m-%d %H:%M:%S UTC')}",
                f"- **Sentiment:** {ce.sentiment:+.2f} (Conf: {ce.confidence:.0%})",
                f"- **Evidence:** _{ev_text}_",
                ""
            ])
            
    lines.extend([
        "---",
        "_Report automatically generated by the Financial Risk NLP Engine._"
    ])
    
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
        
    logger.info(f"Report generated successfully: {out_path}")

if __name__ == "__main__":
    main()
